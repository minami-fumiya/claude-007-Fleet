export interface IShipData {
  id: string;
  /** 通し番号 (#249, src/systems/Numbering.ts): unique across everything numbered; saves keep using `id` */
  no?: number;
  name: string;
  nation: Nation;
  shipClass: ShipClass;
  /** Display / unlock subtype (巡洋戦艦, 重巡, 軽空母 …); mechanics follow `shipClass` */
  subtype?: ShipSubtype;
  hp: number;
  armor: number;
  speed: number;
  weapons: string[];
  spriteKey: string;
  /** Carriers only: embarked aircraft */
  airWing?: IAirWing;
  /** Planned-only design: needs the 架空艦計画 research and never appears in enemy fleets */
  fictional?: boolean;
  /** Short history for the encyclopedia */
  description?: string;
  /** Year the ship (or its class) entered service (#85): ships of a class grow stronger with it */
  year?: number;
  /** A sister ship (#85): same class and performance as this lead ship, generated by scripts/gen-ships.ts */
  sisterOf?: string;
  /**
   * The class a real sister ship belongs to when it keeps stats of its own (no sisterOf), e.g. Tirpitz → bismarck
   * (#246): lists group and number it with that class.
   */
  classOf?: string;
}

export interface IShipStats {
  name: string;
  maxHp: number;
  currentHp: number;
  armor: number;
  speed: number;
  firePower: number;
  shipClass: ShipClass;
  /** Finer type (重巡 / 軽巡 …), for the AI's idea of a target's value (#37) */
  subtype?: ShipSubtype;
  /** Crew proficiency 0..100 (aim and evasion) */
  proficiency?: number;
}
